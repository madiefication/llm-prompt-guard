def generate_augmented_samples(base_list, target_count, label):
    """Augment base samples to reach target count with simple variations."""
    samples = list(base_list)
    augmentation_prefixes = [
        "", "Please ", "Can you ", "Could you ", "I need you to ",
        "Help me: ", "For my project: ", "Tell me: ",
    ]
    augmentation_suffixes = [
        "", " Please respond.", " Thank you.", " I need this urgently.",
        " Be detailed.", " Be concise.", " Explain step by step.",
    ]
    random.seed(42)
    while len(samples) < target_count:
        base = random.choice(base_list)
        prefix = random.choice(augmentation_prefixes)
        suffix = random.choice(augmentation_suffixes)
        variant = f"{prefix}{base}{suffix}".strip()
        if variant not in samples:
            samples.append(variant)
    return [(s, label) for s in samples[:target_count]]


def main():
    random.seed(42)

    benign_samples = generate_augmented_samples(BENIGN_PROMPTS, 300, 0)
    adversarial_samples = generate_augmented_samples(ADVERSARIAL_PROMPTS, 200, 1)

    all_samples = benign_samples + adversarial_samples
    random.shuffle(all_samples)

    out_path = os.path.join(os.path.dirname(__file__), "training_data.csv")
    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["text", "label"])
        writer.writerows(all_samples)

    print(f"Dataset saved to {out_path}")
    print(f"Total samples: {len(all_samples)}")
    print(f"  Benign (0): {sum(1 for _, l in all_samples if l == 0)}")
    print(f"  Adversarial (1): {sum(1 for _, l in all_samples if l == 1)}")


if __name__ == "__main__":
    main()
